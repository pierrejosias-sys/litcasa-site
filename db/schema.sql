-- --------------------------------------------------------------------------
-- Helper: keep updated_at current on UPDATE
-- --------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

-- --------------------------------------------------------------------------
-- products — the 59 products (LC-001..LC-059), seeded by seed.sql
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS products (
  id               text PRIMARY KEY,               -- e.g. 'LC-001'
  name             text NOT NULL,
  category         text NOT NULL,                  -- CSV display name, e.g. 'LED Strips'
  price_cents      integer NOT NULL CHECK (price_cents >= 0),
  typical_price    boolean NOT NULL DEFAULT true,  -- true = placeholder "Typical price*"
  description      text,
  image_url        text,                           -- repo-relative path, e.g. 'images/lc-001.jpg'
  homekit          boolean NOT NULL DEFAULT false, -- true = Apple Home / HomeKit-compatible (smart switches)
  supplier_primary text,
  supplier_backup  text,
  active           boolean NOT NULL DEFAULT true,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE products ADD COLUMN IF NOT EXISTS homekit boolean NOT NULL DEFAULT false;

CREATE INDEX IF NOT EXISTS idx_products_category ON products (category);
CREATE INDEX IF NOT EXISTS idx_products_active   ON products (active);

DROP TRIGGER IF EXISTS trg_products_updated_at ON products;
CREATE TRIGGER trg_products_updated_at
  BEFORE UPDATE ON products
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE products IS 'LitCasa catalogue. price_cents is a starter "typical" price (typical_price=true) until a supplier-confirmed price replaces it.';

-- --------------------------------------------------------------------------
-- customers — one row per buyer email; orders reference email, not this id,
--   so guest checkout still works if no customer row exists yet.
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS customers (
  id         serial PRIMARY KEY,
  email      text NOT NULL UNIQUE,
  name       text,
  phone      text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

DROP TRIGGER IF EXISTS trg_customers_updated_at ON customers;
CREATE TRIGGER trg_customers_updated_at
  BEFORE UPDATE ON customers
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- --------------------------------------------------------------------------
-- orders — one row per checkout. id is LC-YYYYMMDD-NNN, generated by
--   next_order_id() (see order_counters below). shipping_address is TEXT
--   (free-form / JSON string) to keep the schema simple until checkout
--   field layout is finalised.
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS orders (
  id               text PRIMARY KEY,               -- 'LC-YYYYMMDD-NNN'
  customer_name    text NOT NULL,
  customer_email   text NOT NULL,
  customer_phone   text,
  shipping_address text,                           -- text / JSON string
  subtotal_cents   integer NOT NULL DEFAULT 0 CHECK (subtotal_cents >= 0),
  shipping_cents   integer NOT NULL DEFAULT 0 CHECK (shipping_cents >= 0),
  total_cents      integer NOT NULL DEFAULT 0 CHECK (total_cents >= 0),
  status           text NOT NULL DEFAULT 'pending'
                   CHECK (status IN ('pending', 'paid', 'fulfilled', 'shipped', 'delivered', 'cancelled', 'refunded')),
  payment_provider text,                           -- e.g. 'stripe'
  payment_status   text NOT NULL DEFAULT 'unpaid'
                   CHECK (payment_status IN ('unpaid', 'paid', 'refunded', 'failed')),
  stripe_session_id text,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_orders_customer_email ON orders (customer_email);
CREATE INDEX IF NOT EXISTS idx_orders_status         ON orders (status);
CREATE INDEX IF NOT EXISTS idx_orders_created_at     ON orders (created_at);

DROP TRIGGER IF EXISTS trg_orders_updated_at ON orders;
CREATE TRIGGER trg_orders_updated_at
  BEFORE UPDATE ON orders
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();

COMMENT ON TABLE orders IS 'Checkouts. id format LC-YYYYMMDD-NNN, sequential per day via next_order_id().';

-- --------------------------------------------------------------------------
-- order_items — one row per product line on an order. product_name,
--   unit_price_cents and line_total_cents are snapshots taken at checkout,
--   so later price/product changes do not rewrite history. options is
--   the line's configurator options (jsonb, null = plain add) — e.g.
--   { color, size, brightness, finish?, customText? } — normalized
--   server-side by api/_lib/options.js. Two lines for the same product
--   with different options are separate rows here.
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS order_items (
  id               serial PRIMARY KEY,
  order_id         text NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  product_id       text NOT NULL REFERENCES products (id),
  product_name     text NOT NULL,                  -- snapshot at checkout
  quantity         integer NOT NULL CHECK (quantity > 0),
  unit_price_cents integer NOT NULL CHECK (unit_price_cents >= 0),
  line_total_cents integer NOT NULL CHECK (line_total_cents >= 0),
  options          jsonb                           -- configurator options, null = plain add
);

-- Added for the configurator-options fix (Nov 24, 2026): keep this
-- idempotent ALTER alongside the CREATE TABLE above so re-running
-- schema.sql also upgrades databases created before the column existed.
-- Run the same statement once in the Vercel Query editor for the live
-- litcasa-db — the API degrades gracefully (options not persisted)
-- until it has been applied, but options are only stored after it.
ALTER TABLE order_items ADD COLUMN IF NOT EXISTS options jsonb;

CREATE INDEX IF NOT EXISTS idx_order_items_order_id   ON order_items (order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_product_id ON order_items (product_id);

-- --------------------------------------------------------------------------
-- support_messages — contact / support form submissions. order_id is
--   optional (a message may not relate to an order). When an order is
--   deleted, the message is kept and order_id is set to NULL.
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS support_messages (
  id         serial PRIMARY KEY,
  name       text NOT NULL,
  email      text NOT NULL,
  subject    text,
  message    text NOT NULL,
  order_id   text REFERENCES orders (id) ON DELETE SET NULL,
  status     text NOT NULL DEFAULT 'open'
             CHECK (status IN ('open', 'in_progress', 'resolved', 'closed')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_support_messages_email   ON support_messages (email);
CREATE INDEX IF NOT EXISTS idx_support_messages_status  ON support_messages (status);
CREATE INDEX IF NOT EXISTS idx_support_messages_order   ON support_messages (order_id);

-- --------------------------------------------------------------------------
-- order_counters — one row per calendar date; drives the daily LC- sequence.
--   Increment ONLY via next_order_id() (row-locked upsert), never by hand.
-- --------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS order_counters (
  order_date date PRIMARY KEY,
  counter    integer NOT NULL DEFAULT 0 CHECK (counter >= 0)
);

-- --------------------------------------------------------------------------
-- next_order_id() — returns the next LC-YYYYMMDD-NNN id for a date
--   (default: today). Atomic: the INSERT ... ON CONFLICT DO UPDATE locks
--   the day's counter row, so two concurrent calls cannot collide.
--   Example: SELECT next_order_id();  -->  'LC-20261124-001'
--            SELECT next_order_id('2026-11-24'::date);
-- --------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION next_order_id(p_date date DEFAULT CURRENT_DATE)
RETURNS text
LANGUAGE plpgsql
AS $$
DECLARE
  v_counter integer;
BEGIN
  INSERT INTO order_counters (order_date, counter)
  VALUES (p_date, 1)
  ON CONFLICT (order_date)
  DO UPDATE SET counter = order_counters.counter + 1
  RETURNING counter INTO v_counter;

  RETURN 'LC-' || to_char(p_date, 'YYYYMMDD') || '-' || lpad(v_counter::text, 3, '0');
END;
$$;
