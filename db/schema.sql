--   Database for the LitCasa LED-lights dropshipping store (Vercel-native).
--   Run this file FIRST, then seed.sql. Safe to re-run: every statement is
--   idempotent (CREATE TABLE IF NOT EXISTS / CREATE INDEX IF NOT EXISTS /
--   CREATE OR REPLACE FUNCTION / DROP TRIGGER IF EXISTS).
--
-- PRICES ARE PLACEHOLDERS — READ THIS
--   All product prices in seed.sql are starter "typical" prices
--   (products.typical_price = true). They are NOT real supplier prices:
--   no supplier cost, shipping, duty, or landed cost has been confirmed
--   for any product (see litcasa-sku-master.csv — supplier links/costs are
--   still "TO CONFIRM"). Do NOT treat price_cents as a real selling cost
--   or margin basis. Flip typical_price to false only when a real,
--   supplier-confirmed price replaces it.
--
-- ORDER IDs
--   Format: LC-YYYYMMDD-NNN (e.g. LC-20261124-001), sequential per day.
--   Use next_order_id() to generate one — it increments order_counters
--   under a row lock (INSERT ... ON CONFLICT DO UPDATE), so concurrent
--   checkouts cannot get the same number.
--
-- NO CREDENTIALS in this file. Connection is via the Vercel dashboard /
--   POSTGRES_URL env var (see PROVISIONING.md).
